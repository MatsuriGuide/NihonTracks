<h1>よくある質問</h1>

<h2>NihonTracksとは何ですか？</h2>
<p>
    NihonTracksは、日本の音楽動画（公式MV、ライブ、カバー、リリックビデオなど）を集めたコラボレーション型カタログです。
    各動画は1組以上のアーティストに紐づけられ、タグ（音楽ジャンル、言語、ボーカルタイプ）で分類できます。
    コンテンツはコミュニティによって追加・充実され、モデレーターと管理者が監督しています。
</p>

<h2>アーティストはどうやって追加しますか？</h2>
<p>
    アーティスト一覧のページから新規追加のリンクを使うか、YouTubeチャンネルのURL
    （<span class="mono">/channel/UC...</span> または <span class="mono">/@ハンドル</span> 形式）から
    クイック追加ができます。その場合、名前・写真・登録者数が自動的に取得されます。一般ユーザーが
    投稿したページは、公開前に承認が必要です。モデレーターと管理者はこの手順を省略できます。
</p>

<h2>動画はどうやって追加しますか？</h2>
<p>
    動画の手動追加はモデレーターと管理者のみが行え、YouTubeのURLを貼り付けるだけでタイトル・サムネイル・
    再生時間が自動取得され、可能な場合はYouTubeチャンネルからアーティストも自動検出されます。また
    NihonTracksは、既に登録されているアーティストのチャンネルを自動的に監視し、手動操作なしで新しい
    動画を公開します。
</p>

<h2>タグはどのように機能しますか？</h2>
<p>
    タグはカテゴリー（音楽ジャンル、言語、ボーカルタイプ）ごとに分類されています。アーティストのタグは
    新しい動画に自動的にコピーされ、その後は各動画で個別に編集できます。既存タグの一覧は管理者が
    管理しており、重複や不要なバリエーションを防いでいます。
</p>

<h2>プレイリストはどのように機能しますか？</h2>
<p>
    ログイン済みのユーザーは誰でも、公開または非公開のプレイリストを作成し、動画のページから直接
    追加できます。公開プレイリストはサイト上で連続再生することができます。
</p>

<h2>ニュースレターはどのように機能しますか？</h2>
<p>
    動画一覧のページから、ログイン済みのユーザーは誰でも1つ以上のフィルター（アーティスト・動画タイプ・
    タグ）を保存し、どれをメールで受け取るか選択できます。1日1回、チェックしたフィルターのいずれかに
    一致する新しい動画があればまとめてメールが届きます。同じ動画が複数のフィルターに一致しても重複しては
    届かず、新しいものが何もない日にはメールも届きません。各メールには、ワンクリックで配信停止できる
    リンクが記載されています。
</p>

<h2>他の言語でも利用できますか？</h2>
<p>
    インターフェースはフランス語・英語・日本語に対応しています（ページ上部の言語切り替え）。アーティスト
    ページと動画ページはそれぞれの言語で翻訳を持つことができ、翻訳がない場合はフランス語版が代わりに
    表示されます。
</p>

<h2>誤りや不適切なコンテンツはどうやって報告しますか？</h2>
<p>
    すべてのアーティストページと動画には「報告」リンクがあります。報告はモデレーターまたは管理者が
    確認し、該当するコンテンツを修正・非表示・削除することができます。
</p>

<h2>モデレーターになれますか？</h2>
<p>
    モデレーターと管理者の権限は、サイトの運営者が手動で付与します。継続的に貢献していて興味がある方は、
    <a href="mailto:contact@koshiki.art">contact@koshiki.art</a> までご連絡ください。
</p>

<h2>動画やアーティストに表示される情報はどこから来ていますか？</h2>
<p>
    動画のメタデータ（タイトル・サムネイル・再生時間・公開日）とチャンネル情報（写真・登録者数）は
    YouTube APIから直接取得されています。プロフィール・結成年・レーベルは手動で入力するか、AIによる
    提案を利用できますが、AIが誤ることもあるため、保存前に必ず内容を確認してください。
</p>

