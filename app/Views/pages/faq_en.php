<h1>Frequently Asked Questions</h1>

<h2>What is NihonTracks?</h2>
<p>
    NihonTracks is a collaborative catalog of Japanese music videos (official MVs, live performances,
    covers, lyric videos...). Each video is linked to one or more artists and can be classified with tags
    (music genre, language, vocal type). Content is added and improved by the community, under the
    supervision of moderators and administrators.
</p>

<h2>How do I add an artist?</h2>
<p>
    From the artist list, a link lets you add a new one, or do a quick add from a simple YouTube channel
    URL (in the format <span class="mono">/channel/UC...</span> or <span class="mono">/@handle</span>):
    the name, photo, and subscriber count are then fetched automatically. A page submitted by a regular
    user goes through an approval step before appearing publicly; moderators and administrators skip
    that step.
</p>

<h2>How do I add a video?</h2>
<p>
    Manually adding a video is reserved for moderators and administrators, by pasting its YouTube URL:
    title, thumbnail, and duration are fetched automatically, and the artist is detected automatically
    when possible from the YouTube channel. NihonTracks also automatically watches the channels of
    artists already registered and publishes their new videos without any manual step.
</p>

<h2>How do tags work?</h2>
<p>
    Tags are organized into categories (music genre, language, vocal type). An artist's tags are
    automatically copied onto their new videos, and can then be edited independently on each one. The
    list of existing tags is managed by administrators, to avoid duplicates or unnecessary variants.
</p>

<h2>How do playlists work?</h2>
<p>
    Any logged-in user can create playlists, public or private, and add videos to them directly from a
    video's page. A public playlist can be played back to back directly on the site, one video after
    another.
</p>

<h2>How does the newsletter work?</h2>
<p>
    From the video list, any logged-in user can save one or more filters (by artist, video type, or
    tags) and choose which ones to receive by email. Once a day, if new videos match at least one of the
    checked filters, a summary email is sent — never a duplicate if the same video matches several
    filters, and never an email if there's nothing new. A one-click unsubscribe link is included in every
    email.
</p>

<h2>Is the site available in other languages?</h2>
<p>
    The interface is available in French, English, and Japanese (language switcher at the top of the
    page). Artist and video pages can have a translation in each of these languages; when missing, the
    French version is used as a fallback.
</p>

<h2>How do I report an error or inappropriate content?</h2>
<p>
    Every artist page and every video has a "Report" link. The report is then handled by a moderator or
    administrator, who can correct, hide, or delete the content in question.
</p>

<h2>Can I become a moderator?</h2>
<p>
    Moderator and administrator roles are assigned manually by the site's publisher. If you contribute
    regularly and are interested, write to <a href="mailto:contact@koshiki.art">contact@koshiki.art</a>.
</p>

<h2>Where does the information shown on videos and artists come from?</h2>
<p>
    Video metadata (title, thumbnail, duration, release date) and channel data (photo, subscriber count)
    come directly from the YouTube API. Biographies, formation dates, and labels can be filled in
    manually or suggested by AI — always to be checked before saving, since AI can get things wrong.
</p>

